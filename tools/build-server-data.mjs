// Copies the matching core and the prompt bank into the edge function, so the server judges answers
// with exactly the same code and answer list as the game. Run after editing prompts*.js or ff-core.js:
//   node tools/build-server-data.mjs          (write)
//   node tools/build-server-data.mjs --check  (exit 1 if the server copy is out of date)
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, loadBank } from './lib.mjs';

const out = path.join(ROOT, 'supabase/functions/_shared');
const { raw } = loadBank();
const bank = raw.map(p => ({ id: p.id, lvl: p.lvl, cat: p.cat, src: p.src, q: p.q, a: p.a }));
const files = {
  'ff-core.js': fs.readFileSync(path.join(ROOT, 'ff-core.js'), 'utf8'),
  'bank.js': '// generated by tools/build-server-data.mjs — do not edit\nexport const BANK = ' + JSON.stringify(bank) + ';\n',
};
const check = process.argv.includes('--check');
let stale = [];
for (const [f, txt] of Object.entries(files)) {
  const p = path.join(out, f), cur = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
  if (cur !== txt) { stale.push(f); if (!check) { fs.mkdirSync(out, { recursive: true }); fs.writeFileSync(p, txt); } }
}
if (check && stale.length) { console.error('server copy out of date: ' + stale.join(', ') + ' — run node tools/build-server-data.mjs'); process.exit(1); }
console.log(check ? 'server data up to date' : `wrote ${Object.keys(files).join(', ')} (${bank.length} prompts)` + (stale.length ? '' : ' — no changes'));
